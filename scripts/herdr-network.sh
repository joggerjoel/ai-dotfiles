#!/usr/bin/env bash
# herdr-network.sh points herdr's ssh aliases at the LAN or at the tailnet.
#
# herdr saves machines as ssh aliases and runs `ssh -F <tmpfile>`, where the
# tmpfile starts with `Include ~/.ssh/config`. So whatever is in the ssh config
# reaches herdr. OpenSSH keeps the FIRST value it sees for each option, which
# means a block included at the very top of the config beats a later block for
# the same Host.
#
# A "pair" is an alias X (the LAN route) with a sibling alias X-ts (the tailnet
# route) in the same config. In `ts` mode this script writes an override file
# that re-declares `Host X` with the body of `Host X-ts`; in `lan` mode the
# override is empty and the config applies as written. Nothing here names a
# host: the pairs are read from the config.
#
# Usage: herdr-network.sh [auto|lan|ts|status] [--dry-run]
# Env:   SSH_CONFIG                    default $HOME/.ssh/config
#        HERDR_NETWORK_CONF            default $HOME/.ssh/herdr-network.conf
#        HERDR_NETWORK_PROBE_TIMEOUT   seconds per LAN probe, default 2
# Exit:  0 ok, 1 usage, 2 no pairs found.
set -euo pipefail

SSH_CONFIG=${SSH_CONFIG:-$HOME/.ssh/config}
CONF=${HERDR_NETWORK_CONF:-$HOME/.ssh/herdr-network.conf}
PROBE_TIMEOUT=${HERDR_NETWORK_PROBE_TIMEOUT:-2}

usage() {
  echo "usage: ${0##*/} [auto|lan|ts|status] [--dry-run]" >&2
  exit 1
}

MODE=auto
DRY=0
for arg in "$@"; do
  case "$arg" in
    auto | lan | ts | status) MODE=$arg ;;
    --dry-run) DRY=1 ;;
    *) usage ;;
  esac
done

[ -f "$SSH_CONFIG" ] || { echo "no ssh config at $SSH_CONFIG" >&2; exit 2; }

# Emits, per pair in config order of the -ts block:
#   P <TAB> alias <TAB> lan HostName <TAB> lan Port <TAB> ts HostName
#   B <TAB> <ts body line>        (zero or more, verbatim minus indentation)
parse_pairs() {
  awk '
    function opt(body, key,   n, i, a) {
      n = split(body, a, "\n")
      for (i = 1; i <= n; i++) {
        split(a[i], f, /[ \t]+/)
        if (tolower(f[1]) == key) return f[2]
      }
      return ""
    }
    /^[Mm][Aa][Tt][Cc][Hh][ \t]/ { cur = ""; next }
    /^[Hh][Oo][Ss][Tt][ \t]/ {
      cur = ""
      if (NF == 2 && $2 !~ /[*?!]/ && !($2 in body)) {
        cur = $2; body[cur] = ""; order[++n] = cur
      }
      next
    }
    cur != "" && /^[ \t]+[^ \t#]/ {
      line = $0; sub(/^[ \t]+/, "", line)
      body[cur] = body[cur] line "\n"
    }
    END {
      for (i = 1; i <= n; i++) {
        ts = order[i]
        if (ts !~ /-ts$/) continue
        lan = substr(ts, 1, length(ts) - 3)
        if (!(lan in body)) continue
        host = opt(body[lan], "hostname"); if (host == "") host = lan
        port = opt(body[lan], "port");     if (port == "") port = 22
        printf "P\t%s\t%s\t%s\t%s\n", lan, host, port, opt(body[ts], "hostname")
        m = split(body[ts], lines, "\n")
        for (j = 1; j < m; j++) printf "B\t%s\n", lines[j]
      }
    }
  ' "$SSH_CONFIG"
}

ALIASES=() HOSTS=() PORTS=() TSHOSTS=() TSBODY=()
while IFS= read -r row; do
  rest=${row#*$'\t'}
  case "$row" in
    P*)
      IFS=$'\t' read -r a b c d <<<"$rest"
      ALIASES+=("$a") HOSTS+=("$b") PORTS+=("$c") TSHOSTS+=("$d") TSBODY+=("")
      ;;
    B*)
      last=$((${#TSBODY[@]} - 1))
      TSBODY[last]+="$rest"$'\n'
      ;;
  esac
done < <(parse_pairs)

if [ "${#ALIASES[@]}" -eq 0 ]; then
  echo "no alias/alias-ts pairs found in $SSH_CONFIG" >&2
  exit 2
fi

recorded_mode() {
  local m=""
  [ -f "$CONF" ] && m=$(sed -n 's/^# mode: //p' "$CONF" | head -n 1)
  echo "${m:-lan}"
}

if [ "$MODE" = status ]; then
  if [ -f "$CONF" ]; then echo "mode: $(recorded_mode)"; else echo "mode: lan (no override file)"; fi
  for i in "${!ALIASES[@]}"; do
    eff=$(ssh -G -F "$SSH_CONFIG" "${ALIASES[i]}" 2>/dev/null | awk '/^hostname /{print $2}')
    printf '%s\t%s\t(ts: %s)\n' "${ALIASES[i]}" "$eff" "${TSHOSTS[i]:--}"
  done
  exit 0
fi

probe_lan() {
  local dir i nc_opts=(-z)
  # macOS nc's -w is an idle timeout; only -G bounds the connect.
  [ "$(uname -s)" = Darwin ] && nc_opts+=(-G "$PROBE_TIMEOUT")
  nc_opts+=(-w "$PROBE_TIMEOUT")
  dir=$(mktemp -d "${TMPDIR:-/tmp}/herdr-network.XXXXXX")
  for i in "${!ALIASES[@]}"; do
    # a LAN alias that already names the tailnet host answers from anywhere
    [ "${HOSTS[i]}" = "${TSHOSTS[i]}" ] && continue
    (nc "${nc_opts[@]}" "${HOSTS[i]}" "${PORTS[i]}" >/dev/null 2>&1 \
      && echo "${ALIASES[i]} (${HOSTS[i]}:${PORTS[i]})" > "$dir/$i") &
  done
  wait
  local up=0
  for i in "${!ALIASES[@]}"; do
    [ -f "$dir/$i" ] && { echo "LAN answered: $(cat "$dir/$i")" >&2; up=1; }
  done
  rm -rf "$dir"
  [ "$up" -eq 1 ]
}

if [ "$MODE" = auto ]; then
  if probe_lan; then MODE=lan; else echo "no LAN host answered" >&2; MODE=ts; fi
fi

render() {
  echo "# generated by herdr-network.sh, do not edit"
  echo "# mode: $MODE"
  echo "# written: $(date '+%Y-%m-%d %H:%M:%S')"
  [ "$MODE" = ts ] || return 0
  local i
  for i in "${!ALIASES[@]}"; do
    printf '\nHost %s\n' "${ALIASES[i]}"
    printf '%s' "${TSBODY[i]}" | sed 's/^/  /'
  done
}

if [ "$DRY" -eq 1 ]; then
  render
  exit 0
fi

previous=$(recorded_mode)
tmp=$(mktemp "$CONF.XXXXXX")
trap 'rm -f "$tmp"' EXIT
render > "$tmp"
mv "$tmp" "$CONF"
trap - EXIT

INCLUDE_LINE="Include $CONF"
if ! grep -qxF "$INCLUDE_LINE" "$SSH_CONFIG"; then
  backup="$SSH_CONFIG.bak.$(date +%Y%m%d_%H%M%S)"
  cp -p "$SSH_CONFIG" "$backup"
  tmp=$(mktemp "$SSH_CONFIG.XXXXXX")
  trap 'rm -f "$tmp"' EXIT
  cp -p "$SSH_CONFIG" "$tmp"
  { printf '%s\n\n' "$INCLUDE_LINE"; cat "$backup"; } > "$tmp"
  mv "$tmp" "$SSH_CONFIG"
  trap - EXIT
  echo "added '$INCLUDE_LINE' to $SSH_CONFIG (backup: $backup)" >&2
fi

echo "herdr network: $MODE (${#ALIASES[@]} pairs)"
if [ "$previous" != "$MODE" ]; then
  echo "note: existing ssh ControlMaster sessions keep their old route until they close" >&2
fi
